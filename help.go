fmt.Println("  gui                      запустить веб-интерфейс и конструктор этикеток")
fmt.Println("  info                     состояние принтера, заряд и остаток расходников")
fmt.Println("  rfid                     прочитать RFID-метки рулона и красящей ленты")
fmt.Println("  testpage                 встроенная заводская тестовая страница")
fmt.Println("  scan                     найти принтеры NIIMBOT в эфире Bluetooth LE")
